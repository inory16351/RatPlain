def paras(shape):
    if shape.shape_type == 6:  # 그룹
        for s in shape.shapes: yield from paras(s)
    elif shape.has_text_frame:
        yield from shape.text_frame.paragraphs


def set_text(p, t):
    runs = p.runs
    runs[0].text = t
    for r in runs[1:]: r._r.getparent().remove(r._r)


def fix_aspect(sh):
    """그림이 틀 비율과 다르면 가운데를 잘라 맞춤 (cover)"""
    iw, ih = Image.open(io.BytesIO(sh.image.blob)).size
    src, dst = iw / ih, sh.width / sh.height
    if abs(src / dst - 1) < 0.03 or any((sh.crop_left, sh.crop_right, sh.crop_top, sh.crop_bottom)): return False
    if src > dst: sh.crop_left = sh.crop_right = (1 - dst / src) / 2
    else: sh.crop_top = sh.crop_bottom = (1 - src / dst) / 2
    return True


